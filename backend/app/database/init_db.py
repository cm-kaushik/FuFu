import mysql.connector
import os
from dotenv import load_dotenv

load_dotenv()


def init_database():
    """Create database and tables if they don't exist."""
    db_name = os.getenv("DB_NAME", "stock_app")
    host = os.getenv("DB_HOST", "localhost")
    port_env = os.getenv("DB_PORT")
    if port_env:
        port = int(port_env)
    elif "tidbcloud.com" in host:
        port = 4000
    else:
        port = 3306
    user = os.getenv("DB_USER", "root")
    password = os.getenv("DB_PASSWORD", "")

    ssl_kwargs = {}
    ssl_mode = os.getenv("DB_SSL", "").lower()
    is_remote = host not in ("localhost", "127.0.0.1")
    if ssl_mode in ("true", "1", "yes") or (ssl_mode != "false" and is_remote):
        ssl_kwargs["ssl_disabled"] = False
        ssl_kwargs["ssl_verify_cert"] = False

    try:
        # Try connecting directly to the target database (recommended for cloud MySQL like TiDB / Aiven)
        conn = mysql.connector.connect(
            host=host,
            port=port,
            user=user,
            password=password,
            database=db_name,
            **ssl_kwargs
        )
        cursor = conn.cursor()
    except mysql.connector.Error:
        # Fallback for local setup without existing DB
        conn = mysql.connector.connect(
            host=host,
            port=port,
            user=user,
            password=password,
            **ssl_kwargs
        )
        cursor = conn.cursor()
        cursor.execute(f"CREATE DATABASE IF NOT EXISTS {db_name}")
        cursor.execute(f"USE {db_name}")

    # Create users table
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS users (
            id INT AUTO_INCREMENT PRIMARY KEY,
            username VARCHAR(50) UNIQUE NOT NULL,
            email VARCHAR(100) UNIQUE NOT NULL,
            password_hash VARCHAR(255) NOT NULL,
            balance DECIMAL(15, 2) DEFAULT 0.00,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
            INDEX idx_email (email),
            INDEX idx_username (username)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
    """)

    # Create stocks table
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS stocks (
            id INT AUTO_INCREMENT PRIMARY KEY,
            symbol VARCHAR(20) UNIQUE NOT NULL,
            name VARCHAR(100) NOT NULL,
            sector VARCHAR(50),
            exchange VARCHAR(10) DEFAULT 'NSE',
            INDEX idx_symbol (symbol),
            INDEX idx_sector (sector)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
    """)

    # Create holdings table
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS holdings (
            id INT AUTO_INCREMENT PRIMARY KEY,
            user_id INT NOT NULL,
            stock_id INT NOT NULL,
            quantity INT NOT NULL DEFAULT 0,
            avg_buy_price DECIMAL(15, 2) NOT NULL DEFAULT 0.00,
            FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
            FOREIGN KEY (stock_id) REFERENCES stocks(id),
            UNIQUE KEY unique_user_stock (user_id, stock_id),
            INDEX idx_user_id (user_id)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
    """)

    # Create transactions table
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS transactions (
            id INT AUTO_INCREMENT PRIMARY KEY,
            user_id INT NOT NULL,
            stock_id INT DEFAULT NULL,
            type ENUM('BUY', 'SELL', 'DEPOSIT') NOT NULL,
            quantity INT DEFAULT 0,
            price_per_share DECIMAL(15, 2) DEFAULT 0.00,
            total_amount DECIMAL(15, 2) NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
            FOREIGN KEY (stock_id) REFERENCES stocks(id),
            INDEX idx_user_id (user_id),
            INDEX idx_type (type),
            INDEX idx_created_at (created_at)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
    """)

    # ================================================================
    # CUSTOM INDEX TABLES
    # ================================================================

    # Custom indexes created by users
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS custom_indexes (
            id INT AUTO_INCREMENT PRIMARY KEY,
            user_id INT NOT NULL,
            name VARCHAR(100) NOT NULL,
            description TEXT,
            sector VARCHAR(50),
            theme VARCHAR(50),
            universe_size INT NOT NULL,
            top_n INT NOT NULL,
            weight_strategy ENUM('EQUAL', 'MARKET_CAP', 'CUSTOM', 'PERFORMANCE') DEFAULT 'EQUAL',
            rebalance_frequency ENUM('SEMI_ANNUAL') DEFAULT 'SEMI_ANNUAL',
            is_active BOOLEAN DEFAULT TRUE,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
            FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
            INDEX idx_user_id (user_id),
            INDEX idx_theme (theme),
            INDEX idx_sector (sector)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
    """)

    # Index universe constituents
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS index_constituents (
            id INT AUTO_INCREMENT PRIMARY KEY,
            index_id INT NOT NULL,
            stock_id INT NOT NULL,
            custom_weight DECIMAL(5,2) DEFAULT NULL,
            is_active_in_index BOOLEAN DEFAULT TRUE,
            rank_position INT DEFAULT NULL,
            added_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (index_id) REFERENCES custom_indexes(id) ON DELETE CASCADE,
            FOREIGN KEY (stock_id) REFERENCES stocks(id),
            UNIQUE KEY unique_index_stock (index_id, stock_id)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
    """)

    # Index investment positions
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS index_investments (
            id INT AUTO_INCREMENT PRIMARY KEY,
            user_id INT NOT NULL,
            index_id INT NOT NULL,
            total_invested DECIMAL(15,2) DEFAULT 0.00,
            current_value DECIMAL(15,2) DEFAULT 0.00,
            units DECIMAL(15,6) DEFAULT 0.000000,
            nav DECIMAL(15,4) DEFAULT 100.0000,
            status ENUM('ACTIVE', 'REDEEMED') DEFAULT 'ACTIVE',
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
            FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
            FOREIGN KEY (index_id) REFERENCES custom_indexes(id) ON DELETE CASCADE,
            UNIQUE KEY unique_user_index (user_id, index_id)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
    """)

    # Individual stock holdings within an index investment
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS index_holdings (
            id INT AUTO_INCREMENT PRIMARY KEY,
            investment_id INT NOT NULL,
            stock_id INT NOT NULL,
            quantity INT DEFAULT 0,
            allocated_amount DECIMAL(15,2) DEFAULT 0.00,
            weight_percent DECIMAL(5,2) DEFAULT 0.00,
            avg_buy_price DECIMAL(15,2) DEFAULT 0.00,
            FOREIGN KEY (investment_id) REFERENCES index_investments(id) ON DELETE CASCADE,
            FOREIGN KEY (stock_id) REFERENCES stocks(id),
            UNIQUE KEY unique_investment_stock (investment_id, stock_id)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
    """)

    # Index NAV history for performance charts
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS index_value_history (
            id INT AUTO_INCREMENT PRIMARY KEY,
            index_id INT NOT NULL,
            nav DECIMAL(15,4) NOT NULL,
            total_value DECIMAL(15,2) DEFAULT 0.00,
            recorded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (index_id) REFERENCES custom_indexes(id) ON DELETE CASCADE,
            INDEX idx_index_date (index_id, recorded_at)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
    """)

    # Rebalance execution log
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS rebalance_log (
            id INT AUTO_INCREMENT PRIMARY KEY,
            index_id INT NOT NULL,
            investment_id INT NOT NULL,
            rebalance_type ENUM('SEMI_ANNUAL', 'MANUAL') DEFAULT 'SEMI_ANNUAL',
            action VARCHAR(20),
            stock_symbol VARCHAR(20),
            old_weight DECIMAL(5,2),
            new_weight DECIMAL(5,2),
            quantity_change INT DEFAULT 0,
            price_at_rebalance DECIMAL(15,2) DEFAULT 0.00,
            executed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (index_id) REFERENCES custom_indexes(id) ON DELETE CASCADE,
            FOREIGN KEY (investment_id) REFERENCES index_investments(id) ON DELETE CASCADE,
            INDEX idx_index_date (index_id, executed_at)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
    """)

    # AI advisor interaction log
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS ai_advisor_log (
            id INT AUTO_INCREMENT PRIMARY KEY,
            user_id INT NOT NULL,
            context_type ENUM('INDEX_BUY', 'INDEX_SELL', 'STOCK_BUY', 'STOCK_SELL', 'REBALANCE') NOT NULL,
            stock_symbol VARCHAR(20),
            index_id INT,
            query TEXT,
            ai_response TEXT,
            sentiment VARCHAR(20),
            confidence DECIMAL(5,2),
            news_summary TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
            INDEX idx_user_id (user_id),
            INDEX idx_created_at (created_at)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
    """)

